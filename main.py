print("Конвертер единиц")                          # заголовок программы

while True:                                         # цикл, чтобы делать преобразования подряд
    print("\nВыберите тип преобразования:")         # просим выбрать преобразование
    print("1. Километры -> мили")                   # пункт 1
    print("2. Килограммы -> фунты")                 # пункт 2
    print("3. Цельсий -> Фаренгейт")                # пункт 3
    print("4. Метры -> футы")                       # пункт 4
    print("5. Литры -> галлоны")                    # пункт 5
    print("6. Цельсий -> Кельвин")                  # пункт 6
    print("7. Фаренгейт -> Цельсий")                # НОВОЕ: пункт 7
    print("8. Сантиметры -> дюймы")                 # НОВОЕ: пункт 8
    print("9. Часы -> минуты")                      # НОВОЕ: пункт 9

    choice = input("Ваш выбор: ")                   # читаем номер преобразования

    if choice in ("1", "2", "3", "4", "5", "6", "7", "8", "9"):  # проверяем номер (добавили 7, 8, 9)
        try:                                        # пробуем преобразовать ввод в число
            value = float(input("Введите значение: "))  # читаем исходное значение
            if choice == "1":                       # километры -> мили
                result = value * 0.621371           # 1 км = 0.621371 мили
                print(f"{value} км = {result} миль")
            elif choice == "2":                     # килограммы -> фунты
                result = value * 2.20462            # 1 кг = 2.20462 фунта
                print(f"{value} кг = {result} фунтов")
            elif choice == "3":                     # Цельсий -> Фаренгейт
                result = value * 9 / 5 + 32         # формула перевода температуры
                print(f"{value} °C = {result} °F")
            elif choice == "4":                     # метры -> футы
                result = value * 3.28084            # 1 м = 3.28084 фута
                print(f"{value} м = {result} футов")
            elif choice == "5":                     # литры -> галлоны
                result = value * 0.264172           # 1 л = 0.264172 галлона
                print(f"{value} л = {result} галлонов")
            elif choice == "6":                     # Цельсий -> Кельвин
                result = value + 273.15             # K = C + 273.15
                print(f"{value} °C = {result} K")
            elif choice == "7":                     # НОВОЕ: Фаренгейт -> Цельсий
                result = (value - 32) * 5 / 9       # НОВОЕ: обратная формула температуры
                print(f"{value} °F = {result} °C")
            elif choice == "8":                     # НОВОЕ: сантиметры -> дюймы
                result = value / 2.54               # НОВОЕ: 1 дюйм = 2.54 см
                print(f"{value} см = {result} дюймов")
            else:                                   # НОВОЕ: часы -> минуты
                result = value * 60                 # НОВОЕ: в 1 часе 60 минут
                print(f"{value} ч = {result} минут")
        except ValueError:                          # если ввели не число
            print("Ошибка: нужно ввести число.")
    else:                                           # если номер не из списка
        print("Ошибка: неизвестный номер преобразования.")

    while True:                                     # спрашиваем, пока не получим «да» или «нет»
        answer = input("Хотите выполнить ещё одно преобразование? (да/нет): ").strip().lower()  # читаем ответ
        if answer == "да" or answer == "нет":       # ответ правильный
            break                                   # выходим из цикла вопроса
        print("Ошибка: введите «да» или «нет».")    # неправильный ответ, спросим снова

    if answer == "нет":                             # пользователь хочет закончить
        break                                       # выходим из главного цикла

print("Работа программы завершена.")                # сообщение при выходе